param(
  [Parameter(Mandatory=$true)][string]$In,
  [Parameter(Mandatory=$true)][string]$Out
)

# Must stay byte-for-byte identical to kPayloadKey / the decode loop in main.cpp.
$k = @(0x9E,0x21,0x4C,0x77,0x0B,0x63,0xA5,0x3D,0xF1,0x58,0x8C,0x12,0xD4,0x6E,0x27,0xBA,
       0x05,0x94,0xE8,0x33,0x71,0xCF,0x46,0x19,0xAD,0x82,0x5B,0xE0,0x2C,0x69,0xF7,0x3B)

$b = [IO.File]::ReadAllBytes($In)
for ($i = 0; $i -lt $b.Length; $i++) {
  $b[$i] = $b[$i] -bxor ($k[$i % 32] -bxor (($i * 31 + 7) -band 0xFF))
}
[IO.File]::WriteAllBytes($Out, $b)
Write-Output ("masked {0} bytes -> {1}" -f $b.Length, $Out)
