param(
  [Parameter(Mandatory=$true)][string]$KeyHeader,
  [Parameter(Mandatory=$true)][string]$Out
)

# Mirrors tools\harden_payload.ps1: the MSBuild post-build XOR-encrypts
# payload_src.dll with the per-build key in payload_key.h. The loader has to
# undo that layer as well as our own mask, so bake the key in at build time
# rather than hardcoding it (it is regenerated every build).
$kh = Get-Content $KeyHeader -Raw
$km = [regex]::Matches($kh, '0x([0-9a-fA-F]{2})')
if ($km.Count -ne 32) { Write-Error "payload_key.h: expected 32 key bytes, found $($km.Count)"; exit 1 }

$lines = @()
$lines += '// generated by gen_blob_key.ps1 - do not edit'
$lines += '#pragma once'
$lines += 'static const unsigned char kBlobKey[32] = {'
for ($i = 0; $i -lt 32; $i++) {
  $sep = if ($i -lt 31) { ',' } else { '' }
  $lines += ('  0x' + $km[$i].Groups[1].Value.ToLower() + $sep)
}
$lines += '};'
Set-Content -LiteralPath $Out -Value $lines -Encoding ascii
Write-Output ("blob key -> {0}" -f $Out)
